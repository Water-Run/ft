#!/usr/bin/env python3
"""Saved experiment JSON -> animation data. No database or network needed."""
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]


def build():
    pages=json.loads((ROOT/'research/lab/out_03_pages.json').read_text(encoding="utf-8"))
    steps=json.loads((ROOT/'research/lab/out_01_probe.json').read_text(encoding="utf-8"))
    env=next(r for r in steps if r['group']=='environment')['output'][0].split('\t')
    assert env[0]==pages['version']=='9.7.2'
    assert int(env[2])==pages['page_bytes']==16384
    return {'source':'research/lab/out_01_probe.json + out_03_pages.json',
            'version':env[0],'page_bytes':pages['page_bytes'],'snapshot_sha256':pages['sha256'],
            'file_bytes':pages['file_bytes'],'pages':pages['pages'],'indexes':pages['indexes'],
            'experiments':[s for s in steps if s['group'] not in ('setup','schema','restore_baseline')]}


def render():
    return ('// Generated by tools/gen_data.py from recorded experiments; do not edit.\n'
            '(function(root) {\n  const data = '+json.dumps(build(),ensure_ascii=False,indent=2)+';\n'
            '  if (typeof module !== "undefined" && module.exports) module.exports = data;\n'
            '  else root.INNODB_DATA = data;\n})(typeof window !== "undefined" ? window : globalThis);\n')


if __name__=='__main__':
    out=ROOT/'src/js/data.js'; out.parent.mkdir(parents=True,exist_ok=True)
    out.write_text(render(),encoding='utf-8',newline='\n')
    print('Generated src/js/data.js from measured evidence')
