"""Render the Lua logo (no label) to SVG from the official PostScript program.

Source: https://www.lua.org/images/lua-logo-nolabel.ps (fetched by
research/lab/10_materials.py into research/_src/materials/). Geometry and
colours are taken from that program; the word "Lua" is set in TeX Gyre Heros,
a Helvetica metric clone, as the program asks for /Helvetica. The logo terms
(lua.org/images): no modification other than the orbiting text, any scale with
the relative proportions kept, credit to the graphic designer.

Output: src/img/lua-logo.svg (generated; do not edit by hand).
"""

import math
import re
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

VIDEO = Path(__file__).resolve().parent.parent
MAT = VIDEO / "research" / "_src" / "materials"
OUT = VIDEO / "src" / "img" / "lua-logo.svg"


def ps_values(ps):
    rgb = re.search(r"/PLANETCOLOR\s*\{([\d.\s]+)setrgbcolor\}", ps).group(1).split()
    orbit = float(re.search(r"/ORBITCOLOR\s*\{([\d.]+)\s*setgray\}", ps).group(1))
    size = float(re.search(r"/LOGOFONT\s*\{/Helvetica\s+([\d.]+)\}", ps).group(1))
    dash = float(re.search(r"/DASHANGLE\s+([\d.]+)\s+def", ps).group(1))
    lw = float(re.search(r"([\d.]+)\s+setlinewidth", ps).group(1))
    a1, a2 = map(float, re.search(r"3 copy\s+(\d+)\s+(\d+)\s+arcn", ps).groups())
    base = float(re.search(r"LOGO stringwidth pop 2 div neg\s+(-?[\d.]+)\s+moveto", ps).group(1))
    hexc = "#" + "".join(f"{round(float(c) * 255):02X}" for c in rgb)
    return hexc, "#" + f"{round(orbit * 255):02X}" * 3, size, dash, lw, a1, a2, base


def word_path(size, baseline):
    font = TTFont(MAT / "texgyreheros-regular.otf")
    upm = font["head"].unitsPerEm
    glyphs, cmap = font.getGlyphSet(), font.getBestCmap()
    names = [cmap[ord(c)] for c in "Lua"]
    width = sum(glyphs[n].width for n in names) * size / upm
    pen = SVGPathPen(glyphs, ntos=lambda v: f"{v:.4f}".rstrip("0").rstrip("."))
    x = -width / 2  # "LOGO stringwidth pop 2 div neg" : centred
    for n in names:
        s = size / upm
        # PostScript y is up; SVG y is down: flip, baseline at -baseline in SVG units
        glyphs[n].draw(TransformPen(pen, (s, 0, 0, -s, x, -baseline)))
        x += glyphs[n].width * s
    return pen.getCommands()


def main():
    ps = (MAT / "lua-logo-nolabel.ps").read_text(encoding="latin-1")
    planet, orbitc, size, dashangle, lw, a1, a2, base = ps_values(ps)
    r = 1 - math.sqrt(2) / 2                     # moon radius; planet radius is 1
    hole = 1 - 2 * r                             # hole centre (PS coords, y up)
    R = 1 + r                                    # orbit radius
    dash = R * math.pi / 180 * (dashangle / 2)   # [ (1+r)*pi/180*HALFDASHANGLE ] 0 setdash
    # arcn from a1 down to a2 (clockwise in PS, y up): covers 360-(a2-a1) degrees
    sweep = 360 - (a2 - a1)
    x1, y1 = R * math.cos(math.radians(a1)), -R * math.sin(math.radians(a1))
    x2, y2 = R * math.cos(math.radians(a2)), -R * math.sin(math.radians(a2))
    # BoundingBox -45 0 1035 1080 in the program's page units:
    # translate(512,512) then scale 512/sqrt2 per logo unit
    unit = 512 / math.sqrt(2)
    vb = [(-45 - 512) / unit, -(1080 - 512) / unit, 1080 / unit, 1080 / unit]
    f = lambda v: f"{v:.5f}".rstrip("0").rstrip(".")
    svg = f"""<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by tools/gen_logo.py from https://www.lua.org/images/lua-logo-nolabel.ps.
     Lua logo: graphic design by Alexandre Nakonechnyj, copyright (c) 1998 Lua.org.
     Used under the terms on https://www.lua.org/images/ (unmodified, proportions kept).
     Word set in TeX Gyre Heros (GUST Font License), a Helvetica metric clone. -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="{' '.join(f(v) for v in vb)}" role="img" aria-label="Lua">
  <circle cx="0" cy="0" r="1" fill="{planet}"/>
  <circle cx="{f(hole)}" cy="{f(-hole)}" r="{f(r)}" fill="#FFFFFF"/>
  <circle cx="1" cy="-1" r="{f(r)}" fill="{planet}"/>
  <path d="{word_path(size, base)}" fill="#FFFFFF"/>
  <path d="M {f(x1)} {f(y1)} A {f(R)} {f(R)} 0 {1 if sweep > 180 else 0} 1 {f(x2)} {f(y2)}"
        fill="none" stroke="{orbitc}" stroke-width="{f(lw)}" stroke-dasharray="{f(dash)}"/>
</svg>
"""
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(svg, encoding="utf-8", newline="\n")
    print("wrote", OUT.relative_to(VIDEO), planet, orbitc, "sweep", sweep)


if __name__ == "__main__":
    main()
