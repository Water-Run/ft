  function splitParagraph(text, id) {
    const units = text.match(/[^，。！？；：]+[，。！？；：]?/gu) || [];
    const chunks = []; let current = '';
    for (const unit of units) {
      if (captionWidth(unit) > 26) throw new Error('R2 分句过长，需改正文：' + id + ' ' + unit);
      if (current && captionWidth(current + unit) > 26) { chunks.push(current); current = ''; }
      current += unit;
      if (/[。！？；]$/.test(unit)) { chunks.push(current); current = ''; }
    }
    if (current) chunks.push(current);
    return chunks;
  }
