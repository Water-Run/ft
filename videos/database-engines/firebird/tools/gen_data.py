"""Generate public scene data from checked research output; no design choices.

Run after research/lab/15_record_layout.py, 16_usage_context.py, 17_page_map.py, 18_usage_2026.py and 19_dbengines_2026.py. Those scripts
document their ignored input files. Generated JS is data only, not a scene.
"""
import json
from pathlib import Path

video = Path(__file__).resolve().parents[1]
lab = video / "research/lab"
layout = json.loads((lab / "out_15_record_layout.json").read_text(encoding="utf-8"))
usage = json.loads((lab / "out_16_usage_context.json").read_text(encoding="utf-8"))
query = json.loads((lab / "out_13_query_path.json").read_text(encoding="utf-8"))
pages = json.loads((lab / "out_17_page_map.json").read_text(encoding="utf-8"))
usage26 = json.loads((lab / "out_18_usage_2026.json").read_text(encoding="utf-8"))
dbe = json.loads((lab / "out_19_dbengines_2026.json").read_text(encoding="utf-8"))
data = {"version": "Firebird 5.0.4 / ODS 13.1", "usage_context": usage, "usage_2026": {k: v for k, v in usage26.items() if k != "options"}, "dbengines_2026": dbe,
        "record_layout": layout, "query": query,
        "page_map": {k: {"pages": v["pages"], "page_types": v["page_types"], "data_page_231": v["data_page_231"], "tip": v["tip"]} for k, v in pages.items()}}
text = "// Generated by tools/gen_data.py; do not edit.\n" + "(function(root) {\n  const data = "
text += json.dumps(data, ensure_ascii=False, indent=2)
text += ";\n  if (typeof module !== 'undefined' && module.exports) module.exports = data;\n  else root.FIREBIRD_DATA = data;\n})(typeof window !== 'undefined' ? window : globalThis);\n"
(video / "src/js/data.js").write_text(text, encoding="utf-8")
print("Generated src/js/data.js from out_13, out_15, out_16, out_17, out_18 and out_19")
