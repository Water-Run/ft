-- Firebird 5.0.4.1812 (Windows x64) 运行参数实测
-- 连接串走 inet://（Remote 提供程序），库文件由服务器进程持有
-- 口令由 isql 的 -password 传入（run_lab.ps1 现场生成），这里不写明文
CREATE DATABASE 'inet://127.0.0.1:3051/lab/demo.fdb'
  DEFAULT CHARACTER SET UTF8;

SELECT MON$DATABASE_NAME AS DB_NAME,
       MON$PAGE_SIZE AS PAGE_SIZE,
       MON$ODS_MAJOR AS ODS_MAJOR,
       MON$ODS_MINOR AS ODS_MINOR,
       MON$PAGES AS PAGES,
       MON$OLDEST_TRANSACTION AS OLDEST_TXN,
       MON$OLDEST_ACTIVE AS OLDEST_ACTIVE,
       MON$OLDEST_SNAPSHOT AS OLDEST_SNAPSHOT,
       MON$NEXT_TRANSACTION AS NEXT_TXN,
       MON$PAGE_BUFFERS AS PAGE_BUFFERS,
       MON$SQL_DIALECT AS SQL_DIALECT,
       MON$SWEEP_INTERVAL AS SWEEP_INTERVAL,
       MON$READ_ONLY AS READ_ONLY,
       MON$FORCED_WRITES AS FORCED_WRITES,
       MON$RESERVE_SPACE AS RESERVE_SPACE,
       MON$BACKUP_STATE AS BACKUP_STATE,
       MON$CRYPT_PAGE AS CRYPT_PAGE,
       MON$OWNER AS OWNER,
       MON$SEC_DATABASE AS SEC_DATABASE,
       MON$REPLICA_MODE AS REPLICA_MODE
  FROM MON$DATABASE;

SELECT RDB$CHARACTER_SET_NAME AS CHARSET FROM RDB$DATABASE;

-- 服务器进程里的三类 attachment：Cache Writer、Garbage Collector、用户连接
SELECT MON$ATTACHMENT_ID, MON$USER, MON$REMOTE_PROTOCOL
  FROM MON$ATTACHMENTS ORDER BY MON$ATTACHMENT_ID;

COMMIT;
QUIT;
